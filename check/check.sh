#!/bin/sh
# setkernel repo check: does this repository follow the org agent standard?
#
#   1. AGENTS.md starts with the current generated kit:core pointer block (before any "## " section).
#   2. CLAUDE.md imports AGENTS.md: a line that is exactly "@AGENTS.md" (or CLAUDE.md is a
#      symlink to AGENTS.md).
#   3. No hand-copied org skills or subagents under .claude/: the setkernel plugin ships them.
#
# In any repo's CI (public repo, no credentials needed):
#   curl -fsSL https://raw.githubusercontent.com/setkernel/agent-plugins/main/check/check.sh | sh -s -- .
#
# Usage: check.sh [repo-dir]       run the checks (default: current directory); exit 1 on failure
#        check.sh --print-block    print the expected pointer block, to paste into AGENTS.md
#
# POSIX sh and standard utilities only. The block and the name lists come from bin/generate.
set -eu

# >>> generated by bin/generate; do not edit by hand
POINTER_BLOCK=$(cat <<'BLOCK'
<!-- kit:core start -->
**setkernel org rules apply here:** https://github.com/setkernel/agent-plugins/blob/main/rules/org-rules.md
(issue tracking, when to stop, secrets, the end-of-run report). Claude Code also gets them from the
org settings. Everything below this block is specific to this repository. Generated; don't edit it.
<!-- kit:core end -->
BLOCK
)
ORG_SKILLS="review-blockers ship-pr verify"
ORG_AGENTS="explorer reviewer"
# <<< generated

if [ "${1:-}" = --print-block ]; then
  printf '%s\n' "$POINTER_BLOCK"
  exit 0
fi
case "${1:-}" in -*) echo "usage: check.sh [repo-dir] | --print-block" >&2; exit 2 ;; esac
dir=${1:-.}
[ -d "$dir" ] || { echo "check.sh: $dir is not a directory" >&2; exit 2; }
cd "$dir"

failed=0
fail() {
  echo "FAIL $1"
  failed=1
}
pass() {
  echo "ok   $1"
}

# 1. The pointer block.
if [ ! -f AGENTS.md ]; then
  fail "AGENTS.md is missing; create it with the pointer block (check.sh --print-block) at the top"
else
  starts=$(grep -c '^<!-- kit:core .*start -->' AGENTS.md || true)
  # The block as it stands: the first start marker through the next end marker, CRs dropped.
  found=$(tr -d '\r' <AGENTS.md | awk '
    /^<!-- kit:core .*start -->/ && !seen { inside = 1; seen = 1 }
    inside { print }
    inside && /^<!-- kit:core end -->/ { exit }
  ')
  # Line numbers of the start marker and of the first "## " heading (0 when there is none).
  start_line=$(grep -n '^<!-- kit:core .*start -->' AGENTS.md | head -n 1 | cut -d: -f1)
  first_section=$(grep -n '^## ' AGENTS.md | head -n 1 | cut -d: -f1)
  if [ "$starts" -eq 0 ]; then
    fail "AGENTS.md has no kit:core pointer block; paste the output of check.sh --print-block near the top"
  elif [ "$starts" -gt 1 ]; then
    fail "AGENTS.md has $starts kit:core blocks; keep one, the pointer block (check.sh --print-block)"
  elif [ "$found" != "$POINTER_BLOCK" ]; then
    fail "AGENTS.md: the kit:core block is stale or edited; replace it with the output of check.sh --print-block"
  elif [ -n "$first_section" ] && [ "$start_line" -gt "$first_section" ]; then
    fail "AGENTS.md: move the kit:core pointer block to the top, before the first '## ' section"
  else
    pass "AGENTS.md has the current pointer block at the top"
  fi
fi

# 2. CLAUDE.md imports AGENTS.md.
if [ -L CLAUDE.md ] && [ "$(basename "$(readlink CLAUDE.md)")" = AGENTS.md ]; then
  pass "CLAUDE.md is a symlink to AGENTS.md"
elif [ ! -f CLAUDE.md ]; then
  fail "CLAUDE.md is missing; create it with the single line @AGENTS.md"
elif tr -d '\r' <CLAUDE.md | grep -qx '@AGENTS.md'; then
  pass "CLAUDE.md imports @AGENTS.md"
else
  fail "CLAUDE.md does not import AGENTS.md; add a line that is exactly @AGENTS.md"
fi

# 3. No hand-copied org skills or subagents.
copies=""
for name in $ORG_SKILLS; do
  if [ -e ".claude/skills/$name" ] || [ -L ".claude/skills/$name" ]; then
    copies="$copies .claude/skills/$name"
  fi
done
for name in $ORG_AGENTS; do
  if [ -e ".claude/agents/$name.md" ] || [ -L ".claude/agents/$name.md" ]; then
    copies="$copies .claude/agents/$name.md"
  fi
done
if [ -n "$copies" ]; then
  fail "hand-copied org skills/agents (the setkernel plugin ships them; delete these):$copies"
else
  pass "no hand-copied org skills or agents in .claude/"
fi

exit "$failed"
